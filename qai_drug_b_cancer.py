import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.datasets import load_breast_cancer

print("Research environment ready!")

data = load_breast_cancer()

X = pd.DataFrame(
    data.data,
    columns=data.feature_names
)

y = pd.Series(data.target)

print("Dataset loaded!")
print("Rows:", X.shape[0])
print("Columns:", X.shape[1])

print("First 5 samples:")
display(X.head())

print("Dataset information:")
print(X.info())

print("Statistical summary:")
display(X.describe())

missing = X.isnull().sum()

print("Missing values:")
print(missing)

print("Total missing values:", missing.sum())

df = X.copy()

df["diagnosis"] = y.map({
    0: "Malignant",
    1: "Benign"
})

display(df.head())

counts = df["diagnosis"].value_counts()

print(counts)

plt.figure(figsize=(8,5))

sns.countplot(
    data=df,
    x="diagnosis"
)

plt.title("Breast Cancer Sample Distribution")
plt.xlabel("Diagnosis")
plt.ylabel("Number of Samples")

plt.show()

percentage = (
    counts / len(df)
) * 100

print(percentage.round(2))

correlation = X.corr()

print(correlation.head())

plt.figure(figsize=(14,10))

sns.heatmap(
    correlation,
    cmap="coolwarm",
    center=0
)

plt.title("Breast Cancer Feature Correlation")

plt.show()

plt.figure(figsize=(8,5))

sns.scatterplot(
    data=df,
    x="mean radius",
    y="mean area",
    hue="diagnosis"
)

plt.title("Mean Radius vs Mean Area")

plt.show()

corr_pairs = correlation.unstack()

corr_pairs = corr_pairs[
    corr_pairs.index.get_level_values(0)
    != corr_pairs.index.get_level_values(1)
]

print(
    corr_pairs.abs()
    .sort_values(ascending=False)
    .head(10)
)

fig, axes = plt.subplots(2, 2, figsize=(14,10))

# 1. Diagnosis distribution
sns.countplot(
    data=df,
    x="diagnosis",
    ax=axes[0,0]
)
axes[0,0].set_title("Diagnosis Distribution")

# 2. Radius distribution
sns.histplot(
    data=df,
    x="mean radius",
    hue="diagnosis",
    ax=axes[0,1]
)
axes[0,1].set_title("Mean Radius")

# 3. Radius vs area
sns.scatterplot(
    data=df,
    x="mean radius",
    y="mean area",
    hue="diagnosis",
    ax=axes[1,0]
)
axes[1,0].set_title("Radius vs Area")

# 4. Feature correlation
sns.heatmap(
    X.iloc[:, :8].corr(),
    cmap="coolwarm",
    ax=axes[1,1]
)
axes[1,1].set_title("Feature Correlation")

plt.tight_layout()
plt.show()

fig = plt.gcf()

fig.savefig(
    "Day01_Breast_Cancer_Dashboard.png",
    dpi=300,
    bbox_inches="tight"
)

report = f"""
DAY 1 RESEARCH REPORT

Project:
Breast Cancer Diagnostic Data Analysis

Dataset:
Wisconsin Diagnostic Breast Cancer

Total Samples: {len(df)}
Total Features: {len(X.columns)}

Benign Samples:
{(df['diagnosis'] == 'Benign').sum()}

Malignant Samples:
{(df['diagnosis'] == 'Malignant').sum()}

Missing Values:
{X.isnull().sum().sum()}

Tools:
Python, Pandas, NumPy,
Matplotlib, Seaborn, Scikit-learn

Conclusion:
Completed initial exploratory
data analysis of breast cancer
diagnostic measurements.

Limitation:
This dataset does not provide
drug response or ER, PR, HER2
biomarker measurements.
"""

print(report)

with open("Day01_Research_Report.txt", "w") as f:
    f.write(report)

# Save complete breast cancer dataset
df.to_csv(
    "Day01_Breast_Cancer_Dataset.csv",
    index=False
)

print("CSV file saved successfully!")

summary = pd.DataFrame({
    "Metric": [
        "Total Samples",
        "Total Features",
        "Benign Samples",
        "Malignant Samples",
        "Missing Values"
    ],
    "Value": [
        len(df),
        len(X.columns),
        (df["diagnosis"] == "Benign").sum(),
        (df["diagnosis"] == "Malignant").sum(),
        X.isnull().sum().sum()
    ]
})

summary.to_csv(
    "Day01_Research_Summary.csv",
    index=False
)

display(summary)

correlation.to_csv(
    "Day01_Feature_Correlation.csv"
)

print("Correlation CSV saved!")

